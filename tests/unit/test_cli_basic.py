"""Tests for sentinelx CLI basic commands."""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path


def test_sentinelx_help():
    """sentinelx --help exits 0 and shows usage."""
    result = subprocess.run(
        [sys.executable, "-c",
         "import sys; sys.argv=['sentinelx','--help']; from sentinelx_cli.main import main; main()"],
        capture_output=True, text=True)
    assert result.returncode == 0
    assert "sentinelx" in result.stdout
    assert "doctor" in result.stdout
    assert "init" in result.stdout
    assert "site" in result.stdout
    assert "shield" in result.stdout
    assert "escalations" in result.stdout
    assert "agent" in result.stdout


def test_doctor_exits_zero():
    """sentinelx doctor exits 0 on healthy environment."""
    result = subprocess.run(
        [sys.executable, "-c",
         "import sys; sys.argv=['sentinelx','doctor']; from sentinelx_cli.main import main; main()"],
        capture_output=True, text=True)
    # doctor should exit 0 if Python version OK and DB path writable
    assert result.returncode == 0
    assert "Python:" in result.stdout
    assert "All checks PASSED" in result.stdout


def test_init_creates_files(tmp_path: Path):
    """sentinelx init creates both config files."""
    with tempfile.TemporaryDirectory() as tmpdir:
        os.chdir(tmpdir)
        result = subprocess.run(
            [sys.executable, "-c",
             "import sys; sys.argv=['sentinelx','init']; from sentinelx_cli.main import main; main()"],
            capture_output=True, text=True)
        assert result.returncode == 0
        assert (Path("sentinelx.site.yaml")).exists()
        assert (Path("sentinelx.agent.yaml")).exists()


def test_init_refuses_overwrite_without_force(tmp_path: Path):
    """sentinelx init refuses to overwrite without --force."""
    with tempfile.TemporaryDirectory() as tmpdir:
        os.chdir(tmpdir)
        # Create files first
        Path("sentinelx.site.yaml").write_text("# existing")
        Path("sentinelx.agent.yaml").write_text("# existing")
        result = subprocess.run(
            [sys.executable, "-c",
             "import sys; sys.argv=['sentinelx','init']; from sentinelx_cli.main import main; main()"],
            capture_output=True, text=True)
        assert result.returncode == 1
        assert "already exist" in result.stderr
        assert "Use --force to overwrite" in result.stderr


def test_init_force_overwrites(tmp_path: Path):
    """sentinelx init --force overwrites existing files."""
    with tempfile.TemporaryDirectory() as tmpdir:
        os.chdir(tmpdir)
        Path("sentinelx.site.yaml").write_text("# old")
        Path("sentinelx.agent.yaml").write_text("# old")
        result = subprocess.run(
            [sys.executable, "-c",
             "import sys; sys.argv=['sentinelx','init','--force']; from sentinelx_cli.main import main; main()"],
            capture_output=True, text=True)
        assert result.returncode == 0
        content = Path("sentinelx.site.yaml").read_text()
        assert "Generated by: sentinx init" in content


def test_doctor_fake_key_not_in_output():
    """sentinelx doctor never prints fake key values."""
    # Set a fake key in environment
    os.environ["FAKE_TEST_KEY"] = "super_secret_123"
    try:
        result = subprocess.run(
            [sys.executable, "-c",
             "import sys; sys.argv=['sentinelx','doctor']; from sentinelx_cli.main import main; main()"],
            capture_output=True, text=True)
        assert result.returncode == 0
        # The fake key value should NOT appear in output
        assert "super_secret_123" not in result.stdout
        assert "FAKE_TEST_KEY: set" in result.stdout  # but the key name should show
    finally:
        del os.environ["FAKE_TEST_KEY"]
